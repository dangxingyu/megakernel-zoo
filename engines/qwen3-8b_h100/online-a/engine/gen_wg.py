"""Generates engine/wg_gen.h: the Hopper warpgroup MMA (wgmma.mma_async m64nNk16, f32 += bf16 x bf16, both operands
from shared memory through descriptors) as macros over an accumulator array. Run by build.sh.
Instruction form as in CUTLASS (cute/arch/mma_sm90_gmma.hpp); requires -arch=sm_90a."""
import os
out = ["// generated by gen_wg.py: do not edit", "#pragma once"]
for n in (8, 16, 32, 64, 128, 256):
    nreg = n // 2
    regs = ", ".join(f"%{i}" for i in range(nreg))
    outs = ", ".join(f'"+f"((d)[{i}])' for i in range(nreg))
    out.append(f"#define WGMMA_N{n}(d, da, db) asm volatile(\"{{\\n.reg .pred p;\\nsetp.ne.b32 p, %{nreg + 2}, 0;\\n\" \\\n"
               f"  \"wgmma.mma_async.sync.aligned.m64n{n}k16.f32.bf16.bf16 {{{regs}}}, %{nreg}, %{nreg + 1}, p, 1, 1, 0, 0;\\n}}\\n\" \\\n"
               f"  : {outs} : \"l\"(da), \"l\"(db), \"r\"(1) : \"memory\")")
# no instruction: tells the compiler that everything read from d below comes after this point (after the wait)
for n in (8, 16, 32, 64, 128, 256):
    nreg = n // 2
    outs = ", ".join(f'"+f"((d)[{i}])' for i in range(nreg))
    out.append(f"#define WG_TOUCH_N{n}(d) asm volatile(\"\" : {outs} : : \"memory\")")
# with the accumulate flag as an argument (0: D = A B, 1: D += A B)
for n in (8, 128):
    nreg = n // 2
    regs = ", ".join(f"%{i}" for i in range(nreg))
    outs = ", ".join(f'"+f"((d)[{i}])' for i in range(nreg))
    out.append(f"#define WGMMA_N{n}_P(d, da, db, acc) asm volatile(\"{{\\n.reg .pred p;\\nsetp.ne.b32 p, %{nreg + 2}, 0;\\n\" \\\n"
               f"  \"wgmma.mma_async.sync.aligned.m64n{n}k16.f32.bf16.bf16 {{{regs}}}, %{nreg}, %{nreg + 1}, p, 1, 1, 0, 0;\\n}}\\n\" \\\n"
               f"  : {outs} : \"l\"(da), \"l\"(db), \"r\"(acc) : \"memory\")")
# A operand in registers (a: uint4 = the four 32-bit registers of the thread), B from shared memory
for n in (8, 128, 136):
    nreg = n // 2
    regs = ", ".join(f"%{i}" for i in range(nreg))
    outs = ", ".join(f'"+f"((d)[{i}])' for i in range(nreg))
    out.append(f"#define WGMMA_RS_N{n}(d, a, db) asm volatile(\"{{\\n.reg .pred p;\\nsetp.ne.b32 p, %{nreg + 5}, 0;\\n\" \\\n"
               f"  \"wgmma.mma_async.sync.aligned.m64n{n}k16.f32.bf16.bf16 {{{regs}}}, {{%{nreg}, %{nreg + 1}, %{nreg + 2}, %{nreg + 3}}}, %{nreg + 4}, p, 1, 1, 0;\\n}}\\n\" \\\n"
               f"  : {outs} : \"r\"((a).x), \"r\"((a).y), \"r\"((a).z), \"r\"((a).w), \"l\"(db), \"r\"(1) : \"memory\")")
# the same with the accumulate flag as an argument (0: D = A B)
for n in (128,):
    nreg = n // 2
    regs = ", ".join(f"%{i}" for i in range(nreg))
    outs = ", ".join(f'"+f"((d)[{i}])' for i in range(nreg))
    out.append(f"#define WGMMA_RS_N{n}_P(d, a, db, acc) asm volatile(\"{{\\n.reg .pred p;\\nsetp.ne.b32 p, %{nreg + 5}, 0;\\n\" \\\n"
               f"  \"wgmma.mma_async.sync.aligned.m64n{n}k16.f32.bf16.bf16 {{{regs}}}, {{%{nreg}, %{nreg + 1}, %{nreg + 2}, %{nreg + 3}}}, %{nreg + 4}, p, 1, 1, 0;\\n}}\\n\" \\\n"
               f"  : {outs} : \"r\"((a).x), \"r\"((a).y), \"r\"((a).z), \"r\"((a).w), \"l\"(db), \"r\"(acc) : \"memory\")")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "wg_gen.h"), "w").write("\n".join(out) + "\n")
